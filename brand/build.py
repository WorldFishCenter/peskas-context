HERE = Path(__file__).resolve().parent
SRC = HERE / "source"
OUT_DIRS = ["svg", "code", "favicon", "app", "png", "social", "og", "r", "native"]
GENERATED = "Generated by peskas-context/brand/build.py. Don't edit here: change the brand kit, then run brand/sync.py."

MARK = json.loads((SRC / "mark.json").read_text())
WORD = json.loads((SRC / "wordmark.json").read_text())
PRODUCTS = json.loads((SRC / "products.json").read_text())
PAL = {k: v["colours"] for k, v in MARK["palettes"].items()}
NAVY = MARK["navy"]
FONT_URL = "data:font/ttf;base64," + base64.b64encode((SRC / "fonts" / "Sora[wght].ttf").read_bytes()).decode()  # embedded: pages built in memory can't load local files


# ---------------------------------------------------------------- geometry

def outline_polygon(spec):
    """The outline from its Bézier segments, as a polygon."""
    pts, cur = [tuple(spec[0])], tuple(spec[0])
    for seg in spec[1:]:
        if seg[0] == "C":
            c1, c2, p = map(tuple, seg[1:])
            for i in range(1, 61):
                t = i / 60
                pts.append(tuple((1 - t) ** 3 * cur[k] + 3 * (1 - t) ** 2 * t * c1[k] + 3 * (1 - t) * t ** 2 * c2[k] + t ** 3 * p[k] for k in (0, 1)))
            cur = p
        else:
            cur = tuple(seg[1]); pts.append(cur)
    return Polygon(pts).buffer(0)


def hexagon(cx, cy, r):
    return Polygon([(cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a))) for a in range(30, 390, 60)])


def mark_geometry(with_gaps=True):
    """The mark's five regions: four shade bands (tail to head) and the eye, as shapely geometries."""
    sil = outline_polygon(MARK["outline"])
    x0, y0, x1, y1 = sil.bounds
    d = MARK["cell_spacing"]; R = d / math.sqrt(3); dy = d * math.sqrt(3) / 2
    cells = []
    for j in range(-2, int((y1 - y0) / dy) + 4):
        y = y0 + j * dy
        for i in range(-2, int((x1 - x0) / d) + 4):
            x = x0 + i * d + (d / 2 if j % 2 else 0)
            h = hexagon(x, y, R)
            if h.intersects(sil) and h.intersection(sil).area > 0.02 * h.area:
                cells.append((x, y, h))
    ex, ey = MARK["eye_near"]
    eye = min(cells, key=lambda c: (c[0] - ex) ** 2 + (c[1] - ey) ** 2)
    edges = [MARK["solid_x"] - x0, MARK["band_edges"][1] * (x1 - x0), MARK["band_edges"][2] * (x1 - x0)]
    groups = {0: [], 1: [], 2: [], 3: [], "eye": []}
    for x, y, h in cells:
        if (x, y) == eye[:2]:
            groups["eye"].append(h); continue
        f = x - x0
        groups[0 if f < edges[0] else 1 if f < edges[1] else 2 if f < edges[2] else 3].append(h)
    net = None
    if with_gaps:
        lines = []
        for _, _, h in cells:
            c = list(h.exterior.coords)
            lines += [LineString([c[k], c[k + 1]]) for k in range(6)]
        net = unary_union(lines).buffer(MARK["gap"] / 2, cap_style=2, join_style=2)
        net = net.intersection(sil.buffer(-MARK["rim"])).difference(box(x0 - 5, y0 - 5, MARK["solid_x"], y1 + 5))
        net = unary_union([g for g in getattr(net, "geoms", [net]) if g.area >= MARK["min_gap_fragment"]])
    out = {}
    for k, hs in groups.items():
        g = unary_union(hs).intersection(sil)
        out[k] = g.difference(net) if net is not None else g
    return out, sil.bounds


def path_d(geom, prec=2):
    f = lambda v: (f"{v:.{prec}f}").rstrip("0").rstrip(".")
    polys = [geom] if geom.geom_type == "Polygon" else list(getattr(geom, "geoms", []))
    parts = []
    for p in polys:
        if p.is_empty or p.area < 0.05:
            continue
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)[:-1]
            parts.append("M" + " ".join(f"{f(x)} {f(y)}" for x, y in c) + "Z")
    return "".join(parts)


REGIONS = [0, 1, 2, 3, "eye"]
FULL, BOUNDS = mark_geometry(True)
SOLID, _ = mark_geometry(False)
MX0, MY0, MX1, MY1 = BOUNDS
MARK_VB = f"{MX0:g} {MY0:g} {MX1 - MX0:g} {MY1 - MY0:g}"

# the logo: the mark moved into the wordmark's space
L = MARK["lockup"]
S = L["mark_height"] / (MY1 - MY0)
TX = WORD["bbox"][0] - L["gap"] - MX1 * S
TY = L["centre_y"] - (MY0 + MY1) / 2 * S
LOGO_REGIONS = {k: affine_transform(g, [S, 0, 0, S, TX, TY]) for k, g in FULL.items()}
LX0, LY0 = MX0 * S + TX, min(MY0 * S + TY, WORD["bbox"][1])
LX1, LY1 = WORD["bbox"][2], max(MY1 * S + TY, WORD["bbox"][3])
LOGO_VB = f"{LX0:.2f} {LY0:.2f} {LX1 - LX0:.2f} {LY1 - LY0:.2f}"
BASELINE = (WORD["baseline"] - LY0) / (LY1 - LY0)


# ---------------------------------------------------------------- SVG

def paths(regions, pal, wordmark=False):
    out = "".join(f'<path fill="{pal[i]}" d="{path_d(regions[k])}"/>' for i, k in enumerate(REGIONS) if pal[i])
    if wordmark:
        out += f'<path fill="{pal[3]}" d="{WORD["d"]}"/>'
    return out


def svg(vb, body, title="Peskas"):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-labelledby="t"><title id="t">{title}</title>{body}</svg>\n'


def favicon_svg():
    """The small mark, with no gaps, in a square; its palette follows the browser's colour scheme."""
    w = MX1 - MX0 + 2; cy = (MY0 + MY1) / 2
    body = "".join(f'<path class="c{i}" d="{path_d(SOLID[k])}"/>' for i, k in enumerate(REGIONS))
    light, dark = PAL["small_light"], PAL["small_dark"]
    css = " ".join(f".c{i}{{fill:{c}}}" for i, c in enumerate(light))
    css_dark = " ".join(f".c{i}{{fill:{c}}}" for i, c in enumerate(dark))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{MX0 - 1:.2f} {cy - w / 2:.2f} {w:.2f} {w:.2f}">'
            f"<!-- {GENERATED} The small Peskas mark (no gaps, darker tail) for tab icons; the browser's colour scheme picks the palette. -->"
            f"<style>{css} @media (prefers-color-scheme: dark){{{css_dark}}}</style>{body}</svg>\n")


# ---------------------------------------------------------------- code: React component and colour CSS

def component(typed):
    sig = "(props: ComponentProps<\"svg\">)" if typed else "(props)"
    head = f'// {GENERATED}\nimport type {{ ComponentProps }} from "react";\n' if typed else f"// {GENERATED}\n"
    def p(cls, d):
        return f'      <path\n        className="{cls}"\n        d="{d}"\n      />\n'
    cls = ["peskas-fill-1", "peskas-fill-2", "peskas-fill-3", "peskas-fill-4", "peskas-fill-eye"]
    logo = "".join(p(c, path_d(LOGO_REGIONS[k])) for c, k in zip(cls, REGIONS)) + p("peskas-fill-4", WORD["d"])
    mark = "".join(p(c, path_d(FULL[k])) for c, k in zip(cls, REGIONS))
    return (f"{head}\n"
            "/**\n * The official Peskas logo (brand kit: peskas-context/brand): the mark and the wordmark\n"
            " * \"peskas\". Its colours come from peskas-logo.css, light and dark. It draws as an image named\n"
            " * \"Peskas\"; pass aria-hidden when the name is already written beside it.\n */\n"
            f"export function PeskasLogo{sig} {{\n  return (\n"
            f'    <svg viewBox="{LOGO_VB}" role="img" aria-label="Peskas" {{...props}}>\n{logo}    </svg>\n  );\n}}\n\n'
            "/** The Peskas mark alone, for small spaces. */\n"
            f"export function PeskasMark{sig} {{\n  return (\n"
            f'    <svg viewBox="{MARK_VB}" role="img" aria-label="Peskas" {{...props}}>\n{mark}    </svg>\n  );\n}}\n\n'
            "export default PeskasLogo;\n")


CSS_VARIANTS = {
    "peskas-logo.css": None,
    "peskas-logo.dark-class.css": ".dark",
    "peskas-logo.bs-theme.css": '[data-bs-theme="dark"]',
    "peskas-logo.data-theme.css": '[data-theme="dark"]',
}


def css(dark_selector):
    names = ["1", "2", "3", "4", "eye"]
    light = "\n".join(f"  --peskas-{n}: {c};" for n, c in zip(names, PAL["light"]))
    dark = "\n".join(f"  --peskas-{n}: {c};" for n, c in zip(names, PAL["dark"]))
    fills = "\n".join(f".peskas-fill-{n} {{\n  fill: var(--peskas-{n});\n}}" for n in names)
    block = f"\n{dark_selector} {{\n{dark}\n}}\n" if dark_selector else ""
    about = f"light values, and dark ones under {dark_selector}" if dark_selector else "light values only: this app has no dark theme"
    return (f"/* {GENERATED}\n   The Peskas logo's colours ({about}). The head colour (4) is also the wordmark's. */\n"
            f":root {{\n{light}\n}}\n{block}\n{fills}\n")


# ---------------------------------------------------------------- rendering

def fonts_css():
    return f'@font-face{{font-family:Sora;src:url("{FONT_URL}");font-weight:100 800}}'


def render(page, html, w, h, out, transparent=False):
    page.set_viewport_size({"width": w, "height": h})
    page.set_content(html, wait_until="load")
    page.evaluate("document.fonts.ready")
    # pages that set text in Sora must have it loaded (a missing font would fall back silently)
    if "font-family:Sora;font-weight" in html and not page.evaluate("document.fonts.check('400 40px Sora')"):
        raise RuntimeError(f"Sora did not load for {out.name}")
    page.evaluate("window.__fit && window.__fit(); window.__fit = undefined")
    page.wait_for_timeout(150)
    png = page.screenshot(omit_background=transparent, clip={"x": 0, "y": 0, "width": w, "height": h})
    im = Image.open(io.BytesIO(png))
    im = im if transparent else im.convert("RGB")
    out.parent.mkdir(parents=True, exist_ok=True)
    im.save(out, optimize=True)
    return im


def page_html(body, bg="transparent", extra_css=""):
    return f"<!doctype html><html><head><style>{fonts_css()}html,body{{margin:0;background:{bg}}}{extra_css}</style></head><body>{body}</body></html>"


def tile_html(size, share, transparent_bg=False):
    """A navy square with the mark (tile palette) taking `share` of its width."""
    inner = svg(MARK_VB, paths(FULL, PAL["small_dark"]))
    bg = "transparent" if transparent_bg else NAVY
    return page_html(f'<div style="width:{size}px;height:{size}px;background:{bg};display:flex;align-items:center;justify-content:center">'
                     f'<div style="width:{share * size}px">{inner.replace("<svg ", "<svg width=\"100%\" ")}</div></div>')


def logo_svg(pal):
    return svg(LOGO_VB, paths(LOGO_REGIONS, PAL[pal], wordmark=True))


def card_html(w, h, name, line, flag):
    H = 92  # logo height
    base = BASELINE * H
    F = 64
    name_html = f'<span class="n">{name}</span>' if name else ""
    flag_uri = "data:image/svg+xml;base64," + base64.b64encode((SRC / "flags" / f"{flag}.svg").read_bytes()).decode() if flag else ""
    flag_html = f'<img src="{flag_uri}" style="height:44px;border-radius:6px;margin-top:{base - 44 + 2:.1f}px">' if flag else ""
    logo = logo_svg("dark").replace("<svg ", f'<svg style="height:{H if name else 120}px;width:auto;display:block" ')
    css_ = (f".c{{width:{w}px;height:{h}px;background:{NAVY};display:flex;flex-direction:column;align-items:center;justify-content:center;gap:48px}}"
            f".row{{display:flex;align-items:flex-start;gap:26px}}"
            f".n{{font-family:Sora;font-weight:400;font-size:{F}px;line-height:1;color:#b9c8d0;letter-spacing:-0.02em;white-space:nowrap;margin-top:{base - 0.84 * F:.1f}px}}"
            f".t{{font-family:Sora;font-weight:400;font-size:34px;color:#8ccbd0;letter-spacing:-0.01em}}.t b{{font-weight:600}}")
    # a long name shrinks until the row fits the card, staying on the wordmark's baseline
    # (run by render() once the fonts have loaded, so it measures Sora and not a fallback)
    fit = (f"<script>window.__fit=()=>{{const r=document.querySelector('.row'),n=document.querySelector('.n');"
           f"if(r&&n){{let F={F};while(r.getBoundingClientRect().width>{w - 120}&&F>30){{F--;n.style.fontSize=F+'px';n.style.marginTop=({base:.2f}-0.84*F)+'px'}}}}}}</script>")
    return page_html(f'<div class="c"><div class="row">{logo}{name_html}{flag_html}</div><div class="t">{line}</div></div>{fit}', NAVY, css_)


def hex_html(name):
    W, H = 518, 600
    def pts(inset):
        r = W / 2 - inset
        return " ".join(f"{W / 2 + r * math.cos(math.radians(a)):.2f},{H / 2 + (H / 2 - inset / math.cos(math.radians(30))) * math.sin(math.radians(a)):.2f}" for a in range(-90, 270, 60))
    mark = svg(MARK_VB, paths(FULL, PAL["dark"])).replace("<svg ", '<svg style="width:250px;height:auto;display:block;margin-bottom:34px" ')
    css_ = (f".w{{position:relative;width:{W}px;height:{H}px}}.w>svg.hex{{position:absolute;inset:0}}"
            ".c{position:absolute;inset:0;display:flex;flex-direction:column;align-items:center;justify-content:center;padding-top:6px}"
            ".n{font-family:Sora;font-weight:600;font-size:56px;color:#fff;letter-spacing:-0.03em;line-height:1;white-space:nowrap}"
            ".k{font-family:Sora;font-weight:400;font-size:28px;color:#8ccbd0;margin-top:14px}")
    return page_html(f'<div class="w"><svg class="hex" viewBox="0 0 {W} {H}"><polygon points="{pts(0)}" fill="#006d77"/>'
                     f'<polygon points="{pts(14)}" fill="{NAVY}"/></svg><div class="c">{mark}<div class="n">{name}</div>'
                     f'<div class="k">{PRODUCTS["hex_caption"]}</div></div></div>', "transparent", css_)


# ---------------------------------------------------------------- build

def main():
    for d in OUT_DIRS:
        shutil.rmtree(HERE / d, ignore_errors=True)
        (HERE / d).mkdir()
    # vectors
    for suffix, pal in (("", "light"), ("-dark", "dark"), ("-ink", "ink"), ("-white", "white")):
        (HERE / "svg" / f"peskas-mark{suffix}.svg").write_text(svg(MARK_VB, paths(FULL, PAL[pal])))
        (HERE / "svg" / f"peskas-logo{suffix}.svg").write_text(svg(LOGO_VB, paths(LOGO_REGIONS, PAL[pal], wordmark=True)))
    (HERE / "favicon" / "favicon.svg").write_text(favicon_svg())
    (HERE / "code" / "peskas-logo.tsx").write_text(component(True))
    (HERE / "code" / "peskas-logo.jsx").write_text(component(False))
    for name, sel in CSS_VARIANTS.items():
        (HERE / "code" / name).write_text(css(sel))
    # rasters
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        fav = (HERE / "favicon" / "favicon.svg").read_text()
        icons = []
        for n in (16, 32, 48, 96):
            im = render(page, page_html(fav.replace("<svg ", f'<svg width="{n}" height="{n}" ')), n, n, HERE / "favicon" / f"_{n}.png", transparent=True)
            icons.append(im)
        icons[2].save(HERE / "favicon" / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)], append_images=icons[:2])
        (HERE / "favicon" / "_96.png").rename(HERE / "favicon" / "favicon-96x96.png")
        for n in (16, 32, 48):
            (HERE / "favicon" / f"_{n}.png").unlink()
        render(page, tile_html(180, 0.70), 180, 180, HERE / "favicon" / "apple-touch-icon.png")
        for n in (192, 512):
            render(page, tile_html(n, 0.70), n, n, HERE / "app" / f"icon-{n}.png")
            render(page, tile_html(n, 0.58), n, n, HERE / "app" / f"icon-{n}-maskable.png")
        for suffix, pal in (("", "light"), ("-dark", "dark")):
            logo = logo_svg(pal)
            vbw, vbh = LX1 - LX0, LY1 - LY0
            for w in (480, 1200):
                h = round(w * vbh / vbw)
                render(page, page_html(logo.replace("<svg ", f'<svg width="{w}" height="{h}" ')), w, h, HERE / "png" / f"peskas-logo{suffix}-{w}.png", transparent=True)
        peskas = next(c for c in PRODUCTS["cards"] if c["name"] is None)
        for w, h in ((1200, 630), (1280, 640)):
            render(page, card_html(w, h, None, peskas["line"], None), w, h, HERE / "social" / f"peskas-social-{w}x{h}.png")
        for c in PRODUCTS["cards"]:
            render(page, card_html(1200, 630, c["name"], c["line"], c.get("flag")), 1200, 630, HERE / "og" / f"{c['file']}.png")
        for n in PRODUCTS["hexes"]:
            render(page, hex_html(n), 518, 600, HERE / "r" / f"hex-{n}.png", transparent=True)
        # native app sources (@capacitor/assets): icon on navy, foreground inside the adaptive-icon safe zone, splash
        render(page, tile_html(1024, 0.70), 1024, 1024, HERE / "native" / "icon-only.png")
        render(page, tile_html(1024, 0.55, transparent_bg=True), 1024, 1024, HERE / "native" / "icon-foreground.png", transparent=True)
        render(page, page_html(f'<div style="width:1024px;height:1024px;background:{NAVY}"></div>'), 1024, 1024, HERE / "native" / "icon-background.png")
        splash = page_html(f'<div style="width:2732px;height:2732px;background:{NAVY};display:flex;align-items:center;justify-content:center">'
                           f'<div style="width:640px">{logo_svg("dark").replace("<svg ", "<svg width=\"100%\" ")}</div></div>')
        for n in ("splash.png", "splash-dark.png"):
            render(page, splash, 2732, 2732, HERE / "native" / n)
        browser.close()
    print(f"built: logo viewBox {LOGO_VB}, mark viewBox {MARK_VB}, wordmark baseline at {BASELINE:.4f} of the logo height")


if __name__ == "__main__":
    main()
