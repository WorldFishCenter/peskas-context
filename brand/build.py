"""Build every Peskas brand file from source/.

    python build.py

Needs Python 3.10+ with shapely, pillow and playwright (pip install shapely pillow playwright;
python -m playwright install chromium). It rewrites svg/, code/, favicon/, app/, png/, social/, og/,
r/ and native/ from source/mark.json, source/wordmark.json, source/products.json, the font and the
flags. Edit the source, run this, check the files, then run sync.py to copy them into the repos.
"""

